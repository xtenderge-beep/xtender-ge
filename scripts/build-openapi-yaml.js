// Собирает docs/api-v1/openapi.yaml из src/config/openapiV1.js (весь контракт: сделанное и запланированное).
// Запуск: node scripts/build-openapi-yaml.js. Без библиотеки YAML: строки пишутся в двойных кавычках (как JSON),
// это корректный YAML. tests/api-v1-openapi.test.js сверяет файл с кодом.
const fs = require('fs');
const path = require('path');

const OUT = path.join(__dirname, '..', 'docs', 'api-v1', 'openapi.yaml');

function key(name) {
  return /^[A-Za-z_$][A-Za-z0-9_$.-]*$/.test(name) ? name : JSON.stringify(name);
}

function scalar(value) {
  if (value === null || value === undefined) return 'null';
  if (typeof value === 'string') return JSON.stringify(value);
  return String(value);
}

function toYaml(value, indent = '') {
  if (Array.isArray(value)) {
    if (!value.length) return ' []';
    return value.map((item) => {
      if (item && typeof item === 'object' && !Array.isArray(item) && Object.keys(item).length) {
        const [first, ...rest] = toYaml(item, indent + '  ').replace(/^\n/, '').split('\n');
        return '\n' + indent + '- ' + first.trimStart() + (rest.length ? '\n' + rest.join('\n') : '');
      }
      return '\n' + indent + '-' + (item && typeof item === 'object' ? toYaml(item, indent + '  ') : ' ' + scalar(item));
    }).join('');
  }
  if (value && typeof value === 'object') {
    const keys = Object.keys(value).filter((k) => value[k] !== undefined);
    if (!keys.length) return ' {}';
    return keys.map((k) => {
      const v = value[k];
      return '\n' + indent + key(k) + ':' + (v && typeof v === 'object' ? toYaml(v, indent + '  ') : ' ' + scalar(v));
    }).join('');
  }
  return ' ' + scalar(value);
}

function build() {
  const previous = process.env.DOMAIN;
  process.env.DOMAIN = 'xtender.ge';
  try {
    delete require.cache[require.resolve('../src/config/openapiV1')];
    const spec = require('../src/config/openapiV1').spec();
    return '# Generated by scripts/build-openapi-yaml.js from src/config/openapiV1.js — do not edit by hand.\n'
      + '# x-xtender-status: implemented — works now; planned — proposed contract of a later stage (x-xtender-stage).\n'
      + toYaml(spec).replace(/^\n/, '') + '\n';
  } finally {
    if (previous === undefined) delete process.env.DOMAIN; else process.env.DOMAIN = previous;
  }
}

if (require.main === module) {
  fs.mkdirSync(path.dirname(OUT), { recursive: true });
  fs.writeFileSync(OUT, build());
  console.log('Written', path.relative(process.cwd(), OUT));
}

module.exports = { build, toYaml, OUT };
